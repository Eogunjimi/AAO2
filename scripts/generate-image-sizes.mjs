/**
 * Writes src/lib/imageSizes.js: the intrinsic width and height of every file in
 * public/images, so <Img> can emit width/height and prevent layout shift.
 *
 * Run after adding or replacing images:  npm run images:sizes
 */
import { readdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { imageSize } from 'image-size';

const root = fileURLToPath(new URL('..', import.meta.url));
const imagesDir = path.join(root, 'public', 'images');
const outFile = path.join(root, 'src', 'lib', 'imageSizes.js');

async function walk(dir) {
  const entries = await readdir(dir, { withFileTypes: true });
  const files = await Promise.all(
    entries.map((entry) => {
      const full = path.join(dir, entry.name);
      return entry.isDirectory() ? walk(full) : [full];
    }),
  );
  return files.flat();
}

const files = (await walk(imagesDir)).filter((file) => /\.(jpe?g|png|webp|gif|avif)$/i.test(file));
const sizes = {};

for (const file of files.sort()) {
  const { width, height } = imageSize(await readFile(file));
  const urlPath = '/' + path.relative(path.join(root, 'public'), file).split(path.sep).join('/');
  sizes[urlPath] = { width, height };
}

const body = Object.entries(sizes)
  .map(([key, { width, height }]) => `  '${key}': { width: ${width}, height: ${height} },`)
  .join('\n');

await writeFile(
  outFile,
  `// Generated by scripts/generate-image-sizes.mjs — do not edit by hand.\nexport const imageSizes = {\n${body}\n};\n`,
);
console.info(`[image-sizes] wrote ${files.length} entries to src/lib/imageSizes.js`);
